"""Export the registered spline cases as an Ultralytics **YOLO-seg** dataset.

Split protocol (external validation):
  * **test**  = all Halle cases (`UKH…`) — locked, never trained on.
  * **train/val** = Dresden cases, class-stratified patient-level split (one case == one patient).

Label format (one line per lesion): ``<class_id> x1 y1 x2 y2 … xn yn`` with polygon points
normalized to [0, 1] by the image width/height. Images are the de-identified canonical crop.
"""

from __future__ import annotations

import random
from pathlib import Path

import numpy as np

from .. import config as C
from ..data.cohort import build_cohort
from ..labels import register_case


def _write_label(path: Path, class_id: int, polygon: np.ndarray, w: int, h: int) -> None:
    pts = polygon.astype(np.float64).copy()
    pts[:, 0] = np.clip(pts[:, 0] / w, 0, 1)
    pts[:, 1] = np.clip(pts[:, 1] / h, 0, 1)
    coords = " ".join(f"{x:.6f} {y:.6f}" for x, y in pts)
    path.write_text(f"{class_id} {coords}\n")


def _assign_splits(cohort, val_frac: float, seed: int) -> dict[str, str]:
    rng = random.Random(seed)
    splits: dict[str, str] = {}
    dres = cohort[cohort.site == C.SITE_TRAIN]
    for cls in C.CLASSES:
        cases = list(dres[dres["class"] == cls]["case"])
        rng.shuffle(cases)
        n_val = max(1, round(len(cases) * val_frac)) if cases else 0
        for c in cases[:n_val]:
            splits[c] = "val"
        for c in cases[n_val:]:
            splits[c] = "train"
    for c in cohort[cohort.site == C.SITE_TEST]["case"]:
        splits[c] = "test"
    return splits


def export_yolo_seg(
    out_dir: str | Path | None = None,
    *,
    space: str = "crop",
    val_frac: float = 0.2,
    seed: int = 0,
    min_mask_area: int = 30,
) -> dict:
    """Write the dataset under ``out_dir`` (default ``DERIVED/yolo_seg``) and return a summary."""
    import cv2

    out_dir = Path(out_dir or (C.DERIVED / "yolo_seg"))
    for split in ("train", "val", "test"):
        (out_dir / "images" / split).mkdir(parents=True, exist_ok=True)
        (out_dir / "labels" / split).mkdir(parents=True, exist_ok=True)

    cohort = build_cohort()
    df = cohort[cohort.has_spline & (~cohort.excluded.astype(bool))]
    splits = _assign_splits(df, val_frac, seed)

    counts = {s: {c: 0 for c in C.CLASSES} for s in ("train", "val", "test")}
    skipped: list[str] = []
    for _, row in df.iterrows():
        case = row["case"]
        split = splits.get(case)
        if split is None:
            continue
        s = register_case(case, space=space)
        if s is None or s.bbox is None or s.polygon is None or int(s.mask.sum()) < min_mask_area:
            skipped.append(case)
            continue
        img = (np.clip(s.image, 0, 1) * 255).astype(np.uint8)
        h, w = img.shape
        cv2.imwrite(str(out_dir / "images" / split / f"{case}.png"), img)
        _write_label(out_dir / "labels" / split / f"{case}.txt", int(row["class_id"]), s.polygon, w, h)
        counts[split][row["class"]] += 1

    yaml_text = (
        f"# Auto-generated by usloc.datasets.export_yolo\n"
        f"path: {out_dir}\n"
        f"train: images/train\nval: images/val\ntest: images/test\n"
        f"names:\n" + "".join(f"  {i}: {c}\n" for i, c in enumerate(C.CLASSES))
    )
    (out_dir / "dataset.yaml").write_text(yaml_text)

    summary = {
        "out_dir": str(out_dir),
        "counts": counts,
        "totals": {s: sum(counts[s].values()) for s in counts},
        "skipped": skipped,
    }
    return summary
