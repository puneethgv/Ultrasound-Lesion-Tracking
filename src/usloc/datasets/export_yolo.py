"""Export registered spline cases as an Ultralytics **YOLO-seg** dataset.

Split protocol (external validation):
  * **test**  = all Halle cases (`UKH…`) — locked, never trained on.
  * **train/val** = Dresden cases, class-stratified patient-level split (one case == one patient).

Modes:
  * ``multiframe`` — expand each case across its cine (correlation-gated, see ``data.multiframe``).
  * ``class_agnostic`` — collapse all classes to a single ``lesion`` class (localization-only detector).

Label format (one line per lesion): ``<class_id> x1 y1 x2 y2 … xn yn`` with polygon points normalized
to [0, 1] by the image width/height. Images are the de-identified canonical crop. Frames of a patient
never cross splits (splits are assigned per case).
"""

from __future__ import annotations

import random
from pathlib import Path

import numpy as np

from .. import config as C
from ..data.cohort import build_cohort
from ..data.multiframe import iter_case_frames
from ..labels import register_case


def _write_label(path: Path, class_id: int, polygon: np.ndarray, w: int, h: int) -> None:
    pts = polygon.astype(np.float64).copy()
    pts[:, 0] = np.clip(pts[:, 0] / w, 0, 1)
    pts[:, 1] = np.clip(pts[:, 1] / h, 0, 1)
    coords = " ".join(f"{x:.6f} {y:.6f}" for x, y in pts)
    path.write_text(f"{class_id} {coords}\n")


def _assign_splits(cohort, val_frac: float, seed: int) -> dict[str, str]:
    rng = random.Random(seed)
    splits: dict[str, str] = {}
    dres = cohort[cohort.site == C.SITE_TRAIN]
    for cls in C.CLASSES:
        cases = list(dres[dres["class"] == cls]["case"])
        rng.shuffle(cases)
        n_val = max(1, round(len(cases) * val_frac)) if cases else 0
        for c in cases[:n_val]:
            splits[c] = "val"
        for c in cases[n_val:]:
            splits[c] = "train"
    for c in cohort[cohort.site == C.SITE_TEST]["case"]:
        splits[c] = "test"
    return splits


def _case_items(case, space, multiframe, corr_thresh, max_frames):
    """Yield (name, image, polygon, mask) tuples for a case (one for single-frame, many for multi)."""
    if multiframe:
        for s in iter_case_frames(case, corr_thresh=corr_thresh, max_frames=max_frames, space=space):
            yield f"{case}_f{s.frame:03d}", s.image, s.polygon, s.mask
    else:
        s = register_case(case, space=space)
        if s is not None and s.bbox is not None and s.polygon is not None:
            yield case, s.image, s.polygon, s.mask


def export_yolo_seg(
    out_dir: str | Path | None = None,
    *,
    space: str = "crop",
    val_frac: float = 0.2,
    seed: int = 0,
    min_mask_area: int = 30,
    multiframe: bool = False,
    class_agnostic: bool = False,
    corr_thresh: float = 0.85,
    max_frames: int = 40,
) -> dict:
    """Write the dataset under ``out_dir`` (default ``DERIVED/yolo_seg``) and return a summary."""
    import cv2

    out_dir = Path(out_dir or (C.DERIVED / "yolo_seg"))
    for split in ("train", "val", "test"):
        (out_dir / "images" / split).mkdir(parents=True, exist_ok=True)
        (out_dir / "labels" / split).mkdir(parents=True, exist_ok=True)

    names = ["lesion"] if class_agnostic else list(C.CLASSES)
    cohort = build_cohort()
    df = cohort[cohort.has_spline & (~cohort.excluded.astype(bool))]
    splits = _assign_splits(df, val_frac, seed)

    img_counts = {s: 0 for s in ("train", "val", "test")}
    case_counts = {s: 0 for s in ("train", "val", "test")}
    skipped: list[str] = []
    for _, row in df.iterrows():
        case = row["case"]
        split = splits.get(case)
        if split is None:
            continue
        class_id = 0 if class_agnostic else int(row["class_id"])
        wrote = 0
        for name, image, polygon, mask in _case_items(case, space, multiframe, corr_thresh, max_frames):
            if int(mask.sum()) < min_mask_area:
                continue
            img = (np.clip(image, 0, 1) * 255).astype(np.uint8)
            h, w = img.shape
            cv2.imwrite(str(out_dir / "images" / split / f"{name}.png"), img)
            _write_label(out_dir / "labels" / split / f"{name}.txt", class_id, polygon, w, h)
            wrote += 1
        if wrote:
            img_counts[split] += wrote
            case_counts[split] += 1
        else:
            skipped.append(case)

    yaml_text = (
        "# Auto-generated by usloc.datasets.export_yolo\n"
        f"path: {out_dir}\n"
        "train: images/train\nval: images/val\ntest: images/test\n"
        "names:\n" + "".join(f"  {i}: {n}\n" for i, n in enumerate(names))
    )
    (out_dir / "dataset.yaml").write_text(yaml_text)

    return {
        "out_dir": str(out_dir),
        "multiframe": multiframe,
        "class_agnostic": class_agnostic,
        "images": img_counts,
        "cases": case_counts,
        "skipped": skipped,
    }
